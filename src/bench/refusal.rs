    fn word_tokenizer(words: &[&str]) -> tokenizers::Tokenizer {
        use tokenizers::models::wordlevel::WordLevel;
        use tokenizers::pre_tokenizers::whitespace::Whitespace;
        let vocab = std::iter::once("[UNK]")
            .chain(words.iter().copied())
            .enumerate()
            .map(|(i, w)| (w.to_owned(), i as u32))
            .collect();
        let model = WordLevel::builder()
            .vocab(vocab)
            .unk_token("[UNK]".into())
            .build()
            .unwrap();
        let mut tokenizer = tokenizers::Tokenizer::new(model);
        tokenizer.with_pre_tokenizer(Some(Whitespace {}));
        tokenizer
    }

    #[test]
    fn the_first_token_probe_sums_the_prefix_probabilities() {
        // Vocabulary [UNK]=0, I=1, Sorry=2, Sure=3, As=4.
        let tokenizer = word_tokenizer(&["I", "Sorry", "Sure", "As"]);
        let words: Vec<String> = ["I", "Sorry", "I", " ", "As an AI"]
            .map(String::from)
            .to_vec();
        let prefix = prefix_tokens(&tokenizer, &words).unwrap();
        let ids: Vec<u32> = prefix.iter().map(|t| t.id).collect();
        assert_eq!(ids, [1, 2, 4], "first token of each word, once");
        assert_eq!(prefix[2].word, "As an AI");
        assert!(prefix_tokens(&tokenizer, &[" ".into()]).is_err());

        // Probabilities 0.1 (UNK), 0.2 (I), 0.3 (Sorry), 0.35 (Sure), 0.05 (As).
        let logits: Vec<f32> = [0.1f32, 0.2, 0.3, 0.35, 0.05]
            .iter()
            .map(|p| p.ln())
            .collect();
        let score = first_token_score(&logits, &prefix).unwrap();
        assert!((score - 0.55).abs() < 1e-6, "{score}");
        assert!(first_token_score(&[f32::NAN, 0.0], &prefix).is_err());
    }

    #[test]
    fn the_direction_probe_pools_like_the_extraction_then_projects() {
        let rows = vec![vec![1.0f32, 0.0, 2.0], vec![3.0, 1.0, 0.0]];
        let direction = [0.5, 1.0, -1.0];
        // Last position: 1.5 + 1 - 0; mean (2, 0.5, 1): 1 + 0.5 - 1.
        assert_eq!(
            direction_score(&rows, Pooling::Last, &direction).unwrap(),
            2.5
        );
        assert_eq!(
            direction_score(&rows, Pooling::Mean, &direction).unwrap(),
            0.5
        );
        assert!(direction_score(&rows, Pooling::Last, &direction[..2]).is_err());
        assert!(direction_score(&[], Pooling::Mean, &direction).is_err());
    }

