/// The first marker of [`REFUSAL_MARKERS`] found in `text`, if any.
pub fn refusal_marker(text: &str) -> Option<&'static str> {
    markers::find(text, REFUSAL_MARKERS)
}

/// 95 % interval of `p_first − p_second` for paired binary outcomes (Newcombe 1998,
/// method 10): the Wilson intervals of both margins, combined with the correlation φ of the
/// pairs. `both`, `only_first`, `only_second`, `neither` are the four cells of the table.
pub fn newcombe_paired(
    both: usize,
    only_first: usize,
    only_second: usize,
    neither: usize,
) -> (f64, f64) {
    newcombe_paired_z(both, only_first, only_second, neither, super::score::Z_95)
}

/// [`newcombe_paired`] with the normal quantile `z` of the Wilson intervals (two-sided
/// level of the result).
pub fn newcombe_paired_z(
    both: usize,
    only_first: usize,
    only_second: usize,
    neither: usize,
    z: f64,
) -> (f64, f64) {
    let n = both + only_first + only_second + neither;
    if n == 0 {
        return (-1.0, 1.0);
    }
    let (first, second) = (both + only_first, both + only_second);
    let (p1, p2) = (first as f64 / n as f64, second as f64 / n as f64);
    let (l1, u1) = wilson_z(first, n, z);
    let (l2, u2) = wilson_z(second, n, z);
    let (e, f, g, h) = (
        both as f64,
        only_first as f64,
        only_second as f64,
        neither as f64,
    );
    let margins = (e + f) * (g + h) * (e + g) * (f + h);
    let cross = e * h - f * g;
    let half_n = n as f64 / 2.0;
    let phi = if margins == 0.0 {
        0.0
    } else if cross > half_n {
        (cross - half_n) / margins.sqrt()
    } else if cross >= 0.0 {
        0.0
    } else {
        cross / margins.sqrt()
    };
    let (dl1, du1, dl2, du2) = (p1 - l1, u1 - p1, p2 - l2, u2 - p2);
    let diff = p1 - p2;
    // max(0): rounding can leave a tiny negative under the root when φ is close to 1.
    let below = (dl1 * dl1 - 2.0 * phi * dl1 * du2 + du2 * du2)
        .max(0.0)
        .sqrt();
    let above = (du1 * du1 - 2.0 * phi * du1 * dl2 + dl2 * dl2)
        .max(0.0)
        .sqrt();
    ((diff - below).max(-1.0), (diff + above).min(1.0))
}

pub fn score(items: &[RefusalItem]) -> RefusalScore {
    let n = items.len();
    let refused = items.iter().filter(|i| i.refused).count();
    let (ci95_low, ci95_high) = wilson(refused, n);
    RefusalScore {
        n,
        refused,
        refusal_rate: if n == 0 {
            0.0
        } else {
            refused as f64 / n as f64
        },
        ci95_low,
        ci95_high,
    }
}

pub fn paired(main: &[RefusalItem], baseline: &[RefusalItem]) -> RefusalPaired {
    let mut p = RefusalPaired {
        both_refused: 0,
        both_complied: 0,
        unblocked: Vec::new(),
        newly_refused: Vec::new(),
        delta_rate: score(main).refusal_rate - score(baseline).refusal_rate,
        delta_ci95_low: 0.0,
        delta_ci95_high: 0.0,
    };
    for (m, b) in main.iter().zip(baseline) {
        match (b.refused, m.refused) {
            (true, true) => p.both_refused += 1,
            (false, false) => p.both_complied += 1,
            (true, false) => p.unblocked.push(m.index),
            (false, true) => p.newly_refused.push(m.index),
        }
    }
    (p.delta_ci95_low, p.delta_ci95_high) = newcombe_paired(
        p.both_refused,
        p.newly_refused.len(),
        p.unblocked.len(),
        p.both_complied,
    );
    p
}

#[derive(Debug, Clone)]
pub struct RefusalRequest {
    /// Qwen2 directory.
    pub model: PathBuf,
    pub prompts: Vec<String>,
    pub baseline_model: Option<PathBuf>,
    pub max_new_tokens: u32,
    pub chat_template: ChatTemplate,
    /// Active refusal markers; the default is the twelve English ones.
    pub markers: Markers,
    pub generation: GenOptions,
    /// Shown in the report: native, llama-completion or llama-server.
    pub backend: String,
    /// Where the baseline's answers are kept between runs; `None`: always generated.
    pub ref_cache: Option<RefCache>,
}

/// What, besides the model files, changes the answers of a refusal run on `model`: the key
/// of its baseline in the [`RefCache`].
fn cache_inputs(req: &RefusalRequest, model: &Path) -> serde_json::Value {
    let chat = req.chat_template.resolve(model, ChatTemplate::Chatml);
    serde_json::json!({
        "prompts_sha256": prompts_sha256(&req.prompts),
        "chat_template": chat.template.as_str(),
        "chat_system": chat.system,
        "max_new_tokens": req.max_new_tokens,
        "markers": req.markers.all().collect::<Vec<_>>(),
        "backend": req.backend,
        "generation": req.generation.answer_inputs(req.backend == "native"),
    })
}

/// SHA-256 of the prompts as a JSON array of their texts, before any template.
fn prompts_sha256(prompts: &[String]) -> String {
    sha256_hex(
        serde_json::to_string(prompts)
            .unwrap_or_default()
            .as_bytes(),
    )
}

/// Every (prompt, sample), prompt by prompt, through [`TextGenerator::generate_many`]
/// (batched by the native backend, concurrent with llama-server); a generator error
/// stops the suite.
fn run_prompts(
    generator: &mut dyn TextGenerator,
    req: &RefusalRequest,
    format: &PromptFormat,
    cancel: &AtomicBool,
    on_prompt: &mut dyn FnMut(usize, usize),
) -> Result<Vec<RefusalItem>> {
    let samples = req.generation.samples;
    let jobs = req
        .generation
        .jobs(req.prompts.iter().map(|p| format.apply(p)));
    let total = jobs.len();
    let mut done = 0;
    let outcomes = generator.generate_many(
        &jobs,
        req.max_new_tokens,
        cancel,
        &mut |_, _| match cancel.load(Ordering::SeqCst) {
            true => std::ops::ControlFlow::Break(()),
            false => std::ops::ControlFlow::Continue(()),
        },
        &mut |_| {
            done += 1;
            on_prompt(done, total);
        },
    )?;
    if cancel.load(Ordering::SeqCst) {
        return Err(BenchError::Cancelled);
    }
    // A failed generation ends the list: its error comes before the missing items.
    let mut items = Vec::with_capacity(total);
    for (j, outcome) in outcomes.into_iter().enumerate() {
        let outcome = outcome?;
        let marker = req.markers.find(&outcome.text).map(str::to_owned);
        items.push(RefusalItem {
            index: j / samples,
            refused: marker.is_some(),
            marker,
            output: outcome.text,
            sample: (samples > 1).then_some(j % samples),
        });
    }
    if items.len() < total {
        return Err(BenchError::Cancelled);
    }
    Ok(items)
}

/// Baseline first (when given), then the evaluated model, on the same prompts.
pub fn run(
    req: &RefusalRequest,
    make_generator: &mut MakeGenerator<'_>,
    cancel: &AtomicBool,
    on_prompt: &mut dyn FnMut(usize, usize),
) -> Result<BenchRun<BenchRefusalReport>> {
    if req.max_new_tokens == 0 {
        return Err(BenchError::InvalidArgument(
            "--max-new-tokens doit être >= 1".into(),
        ));
    }
    check_texts(req.prompts.clone()).map_err(BenchError::InvalidArgument)?;
    req.generation.validate()?;
    for model in std::iter::once(&req.model).chain(&req.baseline_model) {
        if !model.exists() {
            return Err(BenchError::input(model, "modèle introuvable"));
        }
    }
    let mut evaluate = |model: &Path| -> Result<(Vec<RefusalItem>, u64)> {
        let started = Instant::now();
        let mut generator = make_generator(model)?;
        generator.configure(&req.generation.decoding(None));
        // ChatML when the model declares nothing: what this measure always used.
        let format = req.chat_template.resolve(model, ChatTemplate::Chatml);
        let items = run_prompts(generator.as_mut(), req, &format, cancel, on_prompt)?;
        Ok((items, started.elapsed().as_millis() as u64))
    };
    // The reference is not patched between experiments: read back when nothing changed.
    let mut warnings = Vec::new();
    let baseline = match &req.baseline_model {
        Some(model) => {
            let started = Instant::now();
            let key = match &req.ref_cache {
                Some(_) => ref_cache::key(
                    "refusal",
                    &ref_cache::model_sha256(model)?,
                    cache_inputs(req, model),
                ),
                None => String::new(),
            };
            let cache = req.ref_cache.as_ref();
            let got = ref_cache::cached(cache, &key, "refusal", model, || evaluate(model))?;
            let ms = match got.lookup {
                Lookup::Hit => started.elapsed().as_millis() as u64,
                Lookup::Miss => got.timing_ms,
            };
            warnings = got.notes;
            let cache = cache.map(|_| got.lookup.as_str().to_owned());
            Some((model.clone(), (got.items, ms), cache))
        }
        None => None,
    };
    let (items, total_ms) = evaluate(&req.model)?;
    // Several samples per prompt are not independent pairs: per-prompt rates instead.
    let samples = req.generation.samples;
    let paired_cmp = baseline
        .as_ref()
        .filter(|_| samples == 1)
        .map(|(_, (base, _), _)| paired(&items, base));
    let hits = |items: &[RefusalItem]| by_prompt(items.iter().map(|i| i.refused), samples);
    let generation = (!req.generation.is_historical(req.backend == "native")).then(|| {
        req.generation.report(
            &req.backend,
            Some(&hits(&items)),
            baseline.as_ref().map(|(_, (b, _), _)| hits(b)).as_deref(),
        )
    });
    let chat = req.chat_template.resolve(&req.model, ChatTemplate::Chatml);
    let report = BenchRefusalReport {
        model: req.model.clone(),
        prompts_sha256: prompts_sha256(&req.prompts),
        chat_template: chat.template.as_str().into(),
        chat_system: chat.system,
        max_new_tokens: req.max_new_tokens,
        markers: req.markers.all().map(str::to_owned).collect(),
        score: score(&items),
        items,
        timing_ms: RefusalTiming {
            total: total_ms,
            baseline: baseline.as_ref().map(|(_, (_, ms), _)| *ms),
            judge: None,
        },
        baseline: baseline.map(|(model, (items, _), cache)| RefusalBaseline {
            model,
            score: score(&items),
            items,
            cache,
        }),
        paired: paired_cmp,
        judge: None,
        generation,
    };
    Ok(BenchRun {
        report,
        warnings,
        threshold_warnings: Vec::new(),
    })
}

