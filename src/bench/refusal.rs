    #[test]
    fn a_direction_file_gives_its_layer_wrapping_and_calibrated_threshold() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("refusal.safetensors");
        let write = |meta: &[(&str, &str)]| {
            let meta = meta
                .iter()
                .map(|(k, v)| (k.to_string(), v.to_string()))
                .collect();
            let bytes = crate::extract::encode(&[0.6, 0.8], &meta).unwrap();
            std::fs::write(&path, bytes).unwrap();
        };
        let base = [
            ("layer", "16"),
            ("site", "resid_post"),
            ("pooling", "last"),
            ("chat_template", "chatml"),
            ("pos_mean_proj", "9.0"),
            ("neg_mean_proj", "3.0"),
            ("d_prime", "4.25"),
        ];
        write(&base);
        // Without its companion: the midpoint of the two means.
        let d = read_direction(&path).unwrap();
        assert_eq!(
            (d.info.layer, d.pooling, d.info.calibrated_threshold),
            (16, Pooling::Last, 6.0)
        );
        assert_eq!(d.info.d_prime, Some(4.25));
        assert!((d.values[0] - 0.6).abs() < 1e-6 && (d.values[1] - 0.8).abs() < 1e-6);
        let format = d.format.unwrap();
        assert_eq!(
            (format.template, format.system),
            (ChatTemplate::Chatml, None)
        );
        // With it: the threshold the extraction calibrated.
        let companion = crate::extract::companion_path(&path);
        std::fs::write(&companion, r#"{"schema": 1, "threshold": 5.5}"#).unwrap();
        assert_eq!(
            read_direction(&path).unwrap().info.calibrated_threshold,
            5.5
        );
        // Another site cannot be read back by the native forward.
        let mut other = base;
        other[1] = ("site", "mlp_out");
        write(&other);
        let err = read_direction(&path).unwrap_err().to_string();
        assert!(err.contains("resid_post"), "{err}");
    }
